#!/usr/bin/env python
"""Write results/SUMMARY.md from results/sim_results.json. Every number is formatted from the JSON by this
script (rounded only for display), so the summary cannot drift from the results. Hand-written notes, with no
numbers that are not also printed from the JSON, live in results/SUMMARY_notes.md and are appended verbatim.

Usage (from code/): python write_summary.py [--results ../results]
"""
from __future__ import annotations

import argparse
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PERS = ["general", "jewish", "mideast", "conspiracy"]
METHS = ["true", "naive", "rg_pooled", "rg_strat"]


def f(x, nd=3):
    if x is None:
        return "NA"
    if isinstance(x, str):
        return x
    return f"{x:.{nd}f}"


def pc(x, nd=1):
    return "NA" if x is None else f"{100 * x:.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(HERE, "..", "results"))
    a = ap.parse_args()
    with open(os.path.join(a.results, "sim_results.json")) as fh:
        r = json.load(fh)
    m = r["meta"]
    L = []
    w = L.append
    w("# Simulation study: summary of results (Paper 4, *Supply or Demand?*)\n")
    w("Generated by `code/write_summary.py` from `results/sim_results.json`; every number below is printed from the "
      "JSON (rounded for display only). All data are synthetic: no real platform, item or user was involved.\n")
    w(f"- Versions: {m['versions']}; base seed {m['base_seed']}; seeds `SeedSequence([base_seed, experiment_id, *keys])`, "
      f"experiment ids {m['experiment_seed_ids']}.")
    for run in m["runtime_s"].get("runs", []):
        w(f"- Run of {run['experiments']}: wall {f(run['total_wall'], 1)} s; CPU by part (s): "
          + ", ".join(f"{k}: {f(v, 1) if not isinstance(v, dict) else {kk: round(vv, 1) for kk, vv in v.items() if vv is not None}}"
                      for k, v in run["by_experiment_cpu"].items()))
    ws = m["world_summary"]
    w(f"- World: {ws['n_items']} items, type counts {ws['type_counts']}, item prevalence of antisemitic items "
      f"{f(ws['prevalence_items'])}; background-popularity-weighted prevalence {f(ws['prevalence_bg_weighted'])}, "
      f"borderline {f(ws['borderline_bg_weighted'])}. Impressions per puppet: {m['n_impressions_per_puppet']}.\n")

    if "E1" in r:
        e1 = r["E1"]
        c = e1["config"]
        w("## E1: estimation of AR and AA; misclassification\n")
        w(f"Pools of {c['pool']} puppets per persona x policy cell per classifier regime (no interference); audits resampled "
          f"with U puppets per cell, R = {c['R']} audits per configuration; validation n = {c['n_val']} impressions per "
          f"persona-arm cell (equal allocation over 5 score bands).\n")
        for g, reg in e1["regimes"].items():
            w(f"### Regime {g} ({reg['label']}), reference chron\n")
            w("| persona | true AR (MCSE) | true AA | Se alg/ref | Sp alg/ref | naive AR (pop.) | naive AR formula | "
              "A-opens/puppet alg |")
            w("|---|---|---|---|---|---|---|---|")
            for p in PERS:
                cc = reg["contrasts"]["chron"][p]
                w(f"| {p} | {f(cc['AR'])} ({f(cc['AR_mcse'])}) | {f(cc['AA'], 4)} | {f(cc['se_alg'])}/{f(cc['se_ref'])} | "
                  f"{f(cc['sp_alg'], 4)}/{f(cc['sp_ref'], 4)} | {f(cc['naive_AR_pop'])} | {f(cc['naive_AR_formula'])} | "
                  f"{f(reg['truth'][p]['alg']['opens_A_per_puppet'], 2)} |")
            w("")
            w("| persona | U | method | median AR | median rel. bias % | mean rel. bias % (MCSE) | AR cov. % (MCSE) | "
              "AA bias (MCSE) | AA cov. % | SE ratio |")
            w("|---|---|---|---|---|---|---|---|---|---|")
            for p in PERS:
                for U in ("5", "20", "80"):
                    for mm in METHS:
                        s = reg["contrasts"]["chron"][p]["by_U"][U][mm]
                        AR0 = reg["contrasts"]["chron"][p]["AR"]
                        w(f"| {p} | {U} | {mm} | {f(s['ar_median'])} | {pc(s['ar_relbias_median'])} | "
                          f"{pc(s['ar_relbias'])} ({pc(s['ar_bias_mcse'] / AR0, 2)}) | {pc(s['ar_cov'])} ({pc(s['ar_cov_mcse'])}) | "
                          f"{f(s['aa_bias'], 5)} ({f(s['aa_bias_mcse'], 5)}) | {pc(s['aa_cov'])} | {f(s['se_ratio'], 2)} |")
            w("")
        w("Other references (U = 20, regime ND, true-label estimator: true AR / coverage %):\n")
        for ref in c["refs"]:
            w(f"- {ref}: " + "; ".join(
                f"{p} AR {f(e1['regimes']['ND']['contrasts'][ref][p]['AR'])}, cov {pc(e1['regimes']['ND']['contrasts'][ref][p]['by_U']['20']['true']['ar_cov'])}"
                for p in PERS))
        w("")
        w("Validation-size sensitivity (U = 20, chron, arm-stratified RG: AR coverage % / median rel. bias %):\n")
        for g, reg in e1["regimes"].items():
            w(f"- {g}: " + "; ".join(
                f"{p} " + ", ".join(f"n={nv}: {pc(reg['contrasts']['chron'][p]['n_val_sensitivity'][nv]['rg_strat']['ar_cov'])}/"
                                    f"{pc(reg['contrasts']['chron'][p]['n_val_sensitivity'][nv]['rg_strat']['ar_relbias_median'])}"
                                    for nv in reg['contrasts']['chron'][p]['n_val_sensitivity']) for p in PERS))
        w("")

    if "E1b" in r:
        e = r["E1b"]
        c = e["config"]
        w("## E1b: DESIGN's estimators with session-level data (thm:identify, thm:misclass)\n")
        w(f"Pools of {c['pool']} protocol puppets per persona x arm (alg, chron) with per-session flagged and true shares; "
          f"R = {c['R']} audits per configuration; external validation n1 = {c['n1']}, n0 = {c['n0']}. Estimators: "
          f"AA = (q_alg - q_ref)/J, AR = (q_alg + Sp - 1)/(q_ref + Sp - 1); 'known' uses the pool's realised Se, Sp.\n")
        for nm, reg in e["regimes"].items():
            w(f"### Variant {nm} (classifier {reg['classifier_regime']}, bucket sd {reg['bucket_sd']})\n")
            w("| persona | AR | deff alg/ref | gamma alg/ref | naive AR / omega-formula / kappa-formula | AR_pool formula |")
            w("|---|---|---|---|---|---|")
            for p in PERS:
                v = reg["personas"][p]
                w(f"| {p} | {f(v['AR'])} | {f(v['deff'][0], 2)}/{f(v['deff'][1], 2)} | {f(v['gamma'][0], 3)}/{f(v['gamma'][1], 3)} | "
                  f"{f(v['naive_AR_pop'])} / {f(v['naive_AR_attenuation_formula'])} / {f(v['naive_AR_kappa_formula'])} | {f(v['AR_pool_formula'])} |")
            w("")
            w("| persona | U | estimator | AA cov. cluster / session % | logAR cov. cluster / session % | median AR | sd logAR MC / delta |")
            w("|---|---|---|---|---|---|---|")
            for p in PERS:
                for U, u in reg["personas"][p]["by_U"].items():
                    for k in ("known_pooled", "known_arm"):
                        x = u[k]
                        w(f"| {p} | {U} | {k} | {pc(x['cluster']['AA']['coverage'])} / {pc(x['session']['AA']['coverage'])} | "
                          f"{pc(x['cluster']['logAR']['coverage'])} / {pc(x['session']['logAR']['coverage'])} | {f(x['AR_median'])} | "
                          f"{f(x['logAR_sd_mc'])} / {f(x['cluster']['logAR_se_mean'])} |")
                    for k in ("external_pooled", "external_strat"):
                        x = u[k]
                        w(f"| {p} | {U} | {k} | {pc(x['AA']['coverage'])} (cluster) | {pc(x['logAR']['coverage'])} (cluster) | "
                          f"{f(x['AR_median'])} | {f(x['logAR_sd_mc'])} / {f(x['logAR_sd_delta'])} (median {f(x.get('logAR_sd_delta_median'))}; "
                          f"kappa_Sp {f(x.get('kappa_Sp'))}) |")
            w("")

    if "E2" in r:
        e2 = r["E2"]
        c = e2["config"]
        w("## E2: interference through the shared popularity model\n")
        w(f"{c['U']} puppets per persona x arm (arms alg, {', '.join(c['refs'])}), {c['n_sentinels']} sentinels; R = {c['R']} "
          f"audits per design and traffic share, common random numbers across shares; bias = paired difference from the "
          f"share-0 audit of the same replication. Popularity half-life {c['half_life_days']} day.\n")
        for dn, d in e2["designs"].items():
            w(f"### Design {dn} {d['design']}\n")
            w("| share | load | persona | AA0 (chron) | bias AA chron (SE) | rel. bias % | bias AA popular (SE) | "
              "shift alg | shift popular | Wald cov. chron % |")
            w("|---|---|---|---|---|---|---|---|---|---|")
            for rho, row in d["by_rho"].items():
                for p in PERS:
                    q = row["personas"][p]
                    w(f"| {rho} | {f(row['load']['mean'])} | {p} | {f(q['chron']['AA_truth'], 4)} | "
                      f"{f(q['chron']['bias_AA']['mean'], 4)} ({f(q['chron']['bias_AA']['se'], 4)}) | "
                      f"{pc(q['chron']['rel_bias_AA'])} | {f(q['popular']['bias_AA']['mean'], 4)} ({f(q['popular']['bias_AA']['se'], 4)}) | "
                      f"{f(q['shift']['alg']['mean'], 4)} | {f(q['shift']['popular']['mean'], 4)} | {pc(q['chron']['coverage_wald'])} |")
            w("")
            w("xi (max over grid of |shift| / load): " + "; ".join(
                f"{p}: " + ", ".join(f"{k} {f(v)}" for k, v in d["xi"][p].items()) for p in PERS) + "\n")
        w("Direction (prop:interference(b)), exposure non-increasing in load: " + "; ".join(
            f"{p}: " + ", ".join(f"{arm} {v['non_increasing']}" for arm, v in e2["direction"][p].items()) for p in PERS) + "\n")
        w("Randomised saturation (prop:interference(c)), reference chron: bias naive at l1 / extrapolated (SE), variance ratio:\n")
        for key, sat in e2["saturation"].items():
            w(f"- shares {key}: " + "; ".join(
                f"{p} {f(sat[p]['chron']['bias_naive_l1']['mean'], 4)} / {f(sat[p]['chron']['bias_extrapolated']['mean'], 4)} "
                f"({f(sat[p]['chron']['bias_extrapolated']['se'], 4)}), x{f(sat[p]['chron']['variance_ratio'], 1)}" for p in PERS))
        w("")
        w("Sensitivity interval (prop:interference(d)) with xi_Delta at its simulated value, reference chron "
          "(Wald cov. % -> sensitivity cov. %; mean breakdown xi*):\n")
        for rho, sv in e2["sensitivity"].items():
            w(f"- share {rho}: " + "; ".join(
                f"{p} {pc(sv[p]['chron']['coverage_wald'])} -> {pc(sv[p]['chron']['coverage_sensitivity'])}; xi* {f(sv[p]['chron']['breakdown_xi']['mean'], 3)}"
                for p in PERS))
        if "bounds" in e2:
            w("Post-hoc bounds (computed from this summary by `e2_bounds`), reference chron: curvature zeta (second differences); "
              "extrapolation |bias| vs zeta*l1*l2/2; part (a) |bias AA| vs xi_Delta*l and |bias logAR| vs ratio bound:\n")
            for p in PERS:
                b = e2["bounds"][p]["chron"]
                w(f"- {p}: zeta {f(b['zeta_second_difference'], 4)}; " + "; ".join(
                    f"{k}: {f(v['abs_bias_extrapolated'], 5)} vs {f(v['bound_dd'], 5)}" for k, v in b["saturation"].items())
                  + "; part (a): " + "; ".join(f"share {k}: {f(v['abs_bias_AA'], 5)} vs {f(v['bound_AA'], 5)}, "
                                               f"{f(v['abs_bias_logAR'], 4)} vs {f(v['bound'], 4)}" for k, v in b["part_a"].items()))
            w("")
        ss = e2["sentinel_slope"]
        w(f"\nSentinel slope in load: {f(ss['sentinel'], 4)}; trained alg-arm slopes: "
          + ", ".join(f"{p} {f(ss['trained_arms'][p]['alg'], 4)}" for p in PERS) + "\n")

    if "E3" in r:
        e3 = r["E3"]
        w("## E3: supply/demand decomposition with evolving demand (reference chron)\n")
        w(f"{e3['n_users']} real users (type counts {e3['type_counts']}), cold start, naturalistic choice; demand evolves "
          f"after each formation session; evaluation window {e3['config']['n_eval']} sessions with demand held.\n")
        w(f"- Fixed-demand audit at the initial demand F0 (naturalistic personas): AA {f(e3['AA_ref_F0']['value'], 4)} "
          f"(SE {f(e3['AA_ref_F0']['se'], 4)}), AR {f(e3['AR_ref_F0']['value'])} (SE {f(e3['AR_ref_F0']['se'])}).")
        q = e3["protocol_audit_Q"]
        w(f"- Protocol puppets (avoid-on-flag, E1 pool, regime ND), persona mix {q['weights']}: AA {f(q['AA'], 4)}, AR {f(q['AR'])}.\n")
        w("| H | tau (SE) | tau_sup (SE) | tau_dem (SE) | iota (SE) | phi_sup | phi_dem | TR | Phi_sup | Phi_dem | iota_mult | "
          "audit F0 - tau (SE) | fringe alg/ref | alpha_B alg/ref |")
        w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for H, cp in sorted(e3["checkpoints"].items(), key=lambda t: int(t[0])):
            d = cp["decomposition"]
            g = lambda k, nd=4: f"{f(d[k]['value'], nd)} ({f(d[k]['se'], nd)})"
            w(f"| {H} | {g('tau')} | {g('tau_sup')} | {g('tau_dem')} | {g('iota')} | {f(d['phi_sup']['value'], 4)} | "
              f"{f(d['phi_dem']['value'], 4)} | {f(d['TR']['value'])} | {f(d['Phi_sup']['value'])} | {f(d['Phi_dem']['value'])} | "
              f"{f(d['iota_mult']['value'])} | {f(cp['audit_F0_minus_tau']['value'], 4)} ({f(cp['audit_F0_minus_tau']['se'], 4)}) | "
              f"{f(cp['demand']['alg']['fringe'])}/{f(cp['demand']['ref']['fringe'])} | "
              f"{f(cp['demand']['alg']['alpha_B'])}/{f(cp['demand']['ref']['alpha_B'])} |")
        w("")
        w("Demand-sufficiency gaps (asm:demand), real-user cell minus fixed-demand persona cell, mean (SE):\n")
        for H, cp in sorted(e3["checkpoints"].items(), key=lambda t: int(t[0])):
            w(f"- H = {H}: " + "; ".join(f"{k} {f(v['mean'], 4)} ({f(v['se'], 4)})" for k, v in cp["asm_demand_gap"].items())
              + f"; bilinear check: tau_sup {f(cp['decomposition']['tau_sup']['value'], 4)} vs AA(F_ref) {f(cp['AA_ref_Fref']['value'], 4)}; "
              f"tau_sup + iota {f(cp['decomposition']['tau_sup']['value'] + cp['decomposition']['iota']['value'], 4)} vs AA(F_alg) {f(cp['AA_ref_Falg']['value'], 4)}")
        w("\nPersona-contrast decomposition (protocol puppets, ND pool, vs general persona d0):\n")
        for p, v in e3["persona_contrast"].items():
            w(f"- {p}: total {f(v['total'], 4)} = supply {f(v['supply_contrast'], 4)} + demand {f(v['demand_contrast'], 4)} + "
              f"interaction {f(v['interaction'], 4)} (MCSE {f(v['interaction_mcse'], 4)}); Shapley sup {f(v['phi_sup'], 4)}, dem {f(v['phi_dem'], 4)}")
        w("")

    if "E4" in r:
        e4 = r["E4"]
        c = e4["config"]
        T, TL = c["T"], c["T_long"]
        w("## E4: Markov exposure model (states N, B, A of consumed items)\n")
        w(f"{c['n_acc']} fixed-demand naturalistic accounts per persona x policy; burn-in {c['burn']} sessions; P estimated from "
          f"{c['S']} sessions of T = {T}; validation on one long session of {TL} steps (tail = steps {c['tail_from']}-{TL - 1}); "
          f"bootstrap SEs over accounts (B = {c['n_boot']}).\n")
        w(f"| persona | policy | e_{T} pred (SE) / sim (SE) | e_{TL} pred (SE) / sim | pi_A pred (SE) / tail | P(reach A in {T}) pred / sim | kappa_A | Kemeny K | E_pi tau_A |")
        w("|---|---|---|---|---|---|---|---|---|")
        for p in PERS:
            for pol in ("alg", "chron"):
                x = e4["fit"][p][pol]
                pr, sm, se = x["pred"], x["sim"], x["pred_boot_se"]
                w(f"| {p} | {pol} | {f(pr[f'e_{T}'], 4)} ({f(se[f'e_{T}'], 4)}) / {f(sm['e_T'], 4)} ({f(sm['e_T_se'], 4)}) | "
                  f"{f(pr[f'e_{TL}'], 4)} ({f(se[f'e_{TL}'], 4)}) / {f(sm['e_T_long'], 4)} | {f(pr['pi_A'], 4)} ({f(se['pi_A'], 4)}) / {f(sm['tail'], 4)} | "
                  f"{f(pr['p_reach_20'])} / {f(sm['p_reach_T'])} | {f(pr['kappa_A'])} | {f(pr['kemeny'])} | {f(pr['E_pi_tau_A'], 1)} |")
        w("")
        for kind in ("tilt", "replace"):
            w(f"Perturbation ({kind}): eps | model delta pi_A | identity | first order | bound kappa_A*||E|| | sim delta (tail) | "
              f"model delta e_{T} / bound (e) | sim delta e_{T}" + (" | thm(c) exact pi_A / sim tail" if kind == "replace" else "") + "\n")
            for p in PERS:
                v = e4["perturbation"][kind][p]
                w(f"- {p} (base pi_A {f(v['base_pi_A'], 4)}, kappa_A {f(v['base_kappa_A'])}, E_pi tau_A {f(v['base_E_pi_tau_A'], 1)}):")
                for row in v["rows"]:
                    mo = row["model"]
                    s = (f"  - eps {row['eps']}: {f(mo['delta_A'], 4)} | {f(mo['identity_A'], 4)} | {f(mo['first_order_A'], 4)} | "
                         f"{f(mo['bound_A'], 4)} | {f(row['sim_delta_tail'], 4)} | {f(mo['delta_eT'], 4)} / {f(mo['bound_eT'], 4)} | "
                         f"{f(row['sim_delta_eT'], 4)}")
                    if kind == "replace" and row.get("pred_c_exact_piA") is not None:
                        s += f" | {f(row['pred_c_exact_piA'], 4)} / {f(row['sim_tail'], 4)}"
                    w(s)
            w("")

    if "E5" in r:
        e5 = r["E5"]
        c = e5["config"]
        w("## E5: sequential audit (alg:sequential, Algorithm 1), reference chron\n")
        w(f"Pairs resampled from the E1 pools (regimes {c['regimes']}); waves of {c['wave']} pairs; m = {c['m']} coded flagged "
          f"positions per puppet; Y_u = Qbar_u * Phat_u; R = {c['R']} audits (betting R = {c['R_bet']}); N_max = {c['N_max']} pairs; "
          f"mixture tuned to t* = {c['t_star']}; c_alpha = {e5['c_alpha']}; protocol alpha = {c['alpha_protocol']}, delta = {c['delta']}, "
          f"W_max = {c['W_max']}. 'null' = both arms drawn from the reference pool (AR = 1).\n")
        w("| persona | regime | case | AR | lambda_S | variant | coverage all waves % (MCSE) | coverage to W_max % | "
          "P(excl. 1) wave 2/4/8/16/40 % | median width wave 8 / 80 |")
        w("|---|---|---|---|---|---|---|---|---|---|")
        for p in PERS:
            for g, rr in e5["personas"][p].items():
                for case in ("alt", "null"):
                    if case not in rr:
                        continue
                    for k, v in rr[case].items():
                        if not k.startswith("a0"):
                            continue
                        ex = v["excludes_0_by_wave"]
                        mw = v["median_width_by_wave"]
                        w(f"| {p} | {g} | {case} | {f(rr['AR'])} | {f(rr['lambda_S'])} | {k} | {pc(v['coverage_all_waves'])} "
                          f"({pc(v['coverage_all_waves_mcse'])}) | {pc(v['coverage_to_Wmax'])} | "
                          + "/".join(pc(ex.get(x)) for x in ("2", "4", "8", "16", "40")) + f" | {f(mw.get('8'), 2)} / {f(mw.get('80'), 2)} |")
        w("")
        w("Stopping and conclusions (rules S1-S2, tab:prot-decisions); wrong = conclusion contradicted by the true AR:\n")
        for p in PERS:
            for g, rr in e5["personas"][p].items():
                for case in ("alt", "null"):
                    if case not in rr:
                        continue
                    for k, v in rr[case].items():
                        for kk in [x for x in v if isinstance(v, dict) and x.startswith("W_max_")]:
                            d = v[kk]
                            w(f"- {p} {g} {case} {k} {kk}: mean stop wave {f(d['mean_stop_wave'], 2)}, stopped early "
                              f"{pc(d['stopped_early'])}%, wrong {pc(d['wrong_conclusion'], 2)}% (MCSE {pc(d['wrong_conclusion_mcse'], 2)}); "
                              + ", ".join(f"{a_} {pc(b_)}%" for a_, b_ in d["decisions"].items()))
        w("\nPeeking (fixed-sample 95% interval on the same statistic after every wave) and comparators:\n")
        for p in PERS:
            for g, rr in e5["personas"][p].items():
                for case in ("alt", "null"):
                    if case not in rr:
                        continue
                    pk = rr[case]["peeking"]
                    s_ = (f"- {p} {g} {case}: peeking coverage waves 1-8 {pc(pk['coverage_waves_1_to_Wmax'])}%, waves 2-8 "
                          f"{pc(pk['coverage_waves_2_to_Wmax'])}%, all waves {pc(pk['coverage_all_waves'])}%, single look wave 8 "
                          f"{pc(pk['coverage_single_look_wave8'])}%; rejects AR = 1 by wave 8 {pc(pk['rejects_AR1_by_Wmax'])}%, by last wave "
                          f"{pc(pk['rejects_AR1_by_last_wave'])}%")
                    if "betting_exact" in rr[case]:
                        b = rr[case]["betting_exact"]
                        s_ += (f"; exact betting coverage {pc(b['coverage_all_t'])}%, median log-width t=40/200/400 "
                               + "/".join(f(b["median_log_width"].get(t), 2) for t in ("40", "200", "400"))
                               + ", P(excl. 1) " + "/".join(pc(b["excludes_1_by"].get(t)) for t in ("40", "200", "400")) + "%")
                    if "aa_cs" in rr[case]:
                        a_ = rr[case]["aa_cs"]
                        s_ += (f"; AA plug-in CS (b = 1) coverage {pc(a_['coverage_after_burn_in'])}% (MCSE {pc(a_['coverage_mcse'])}), "
                               f"excludes 0 by wave 8 {pc(a_['excludes_0_by_wave8'])}%")
                    w(s_)
        w("\nPower (prop:power(c),(d); detection of the persona's AR against 1, alpha = 0.05, lambda_S = 1):\n")
        for p in PERS:
            pw = e5["personas"][p]["ND"]["alt"]["power"]
            w(f"- {p}: L {f(pw['L'], 4)}; A_Y formula {f(pw['A_Y_formula'], 4)}, direct {f(pw['A_Y_direct'], 4)}; n_fix {f(pw['n_fix_Y'], 1)}, "
              f"n_seq {f(pw['n_seq_Y'], 1)}, n_seq with lambda range {f(pw.get('n_seq_Y_lam5'), 1)}; fixed-sample power at n_fix "
              f"{f(pw.get('fixed_power_at_n_fix_Y'))}; sequential power by horizon ({pw.get('horizon_waves')} waves) "
              f"{f(pw.get('seq_power_by_horizon'))}, mean stop {f(pw.get('seq_mean_stop_pairs'), 1)} pairs "
              f"({f(pw.get('seq_mean_stop_over_n_fix'), 2)} x n_fix)")
        w("")
    notes = os.path.join(a.results, "SUMMARY_notes.md")
    if os.path.exists(notes):
        with open(notes) as fh:
            w(fh.read())
    with open(os.path.join(a.results, "SUMMARY.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
